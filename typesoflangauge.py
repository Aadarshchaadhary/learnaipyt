#Explicit Type Conversion
#When the programmer manually changes one data type into another.
a = 5
b = float(a)
print(b)

#Implicit Type Conversion
#When Python automatically changes the data type when needed.
a = 5
b = 2.5
c = a + b
print(c)

name = "Addie"
